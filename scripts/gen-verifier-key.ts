/**
 * Bake the Groth16 verification key into the Algorand Python contract as constants
 * (contracts/verifier_key.py). Points are encoded in the AVM's BN254 format:
 *   G1 = X||Y (32-byte BE each); G2 = X.c0||X.c1||Y.c0||Y.c1.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { bigIntToBytes, bytesToHex, NUM_PUBLIC_SIGNALS } from "@nodelink/shared";

interface VerificationKeyJson {
  protocol: string;
  curve: string;
  nPublic: number;
  vk_alpha_1: string[];
  vk_beta_2: string[][];
  vk_gamma_2: string[][];
  vk_delta_2: string[][];
  IC: string[][];
}

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const vk = JSON.parse(readFileSync(resolve(root, "circuits/artifacts/verification_key.json"), "utf8")) as VerificationKeyJson;

if (vk.protocol !== "groth16" || vk.curve !== "bn128") throw new Error("unexpected verification key");
if (vk.nPublic !== NUM_PUBLIC_SIGNALS) throw new Error(`expected ${NUM_PUBLIC_SIGNALS} public signals, got ${vk.nPublic}`);

const fe = (s: string | undefined): string => {
  if (s === undefined) throw new Error("malformed vk");
  return bytesToHex(bigIntToBytes(BigInt(s), 32));
};
const g1 = (p: string[] | undefined): string => {
  if (!p) throw new Error("malformed vk");
  return fe(p[0]) + fe(p[1]);
};
const g2 = (p: string[][]): string => {
  const [x, y] = p;
  if (!x || !y) throw new Error("malformed vk");
  return fe(x[0]) + fe(x[1]) + fe(y[0]) + fe(y[1]);
};

const icRest = vk.IC.slice(1).map(g1).join("");
const out = `# AUTO-GENERATED by scripts/gen-verifier-key.ts from circuits/artifacts/verification_key.json
# DO NOT EDIT. Re-run \`npm run circuit:build\` to regenerate.
#
# !!! DEV-ONLY TRUSTED SETUP !!! This key comes from a single-party local setup and
# MUST be replaced by the output of a multi-party ceremony before any production use.
from algopy import Bytes, subroutine


@subroutine
def vk_alpha_g1() -> Bytes:
    return Bytes.from_hex("${g1(vk.vk_alpha_1)}")


@subroutine
def vk_beta_g2() -> Bytes:
    return Bytes.from_hex("${g2(vk.vk_beta_2)}")


@subroutine
def vk_gamma_g2() -> Bytes:
    return Bytes.from_hex("${g2(vk.vk_gamma_2)}")


@subroutine
def vk_delta_g2() -> Bytes:
    return Bytes.from_hex("${g2(vk.vk_delta_2)}")


@subroutine
def vk_ic0_g1() -> Bytes:
    return Bytes.from_hex("${g1(vk.IC[0])}")


@subroutine
def vk_ic_rest_g1() -> Bytes:
    # IC[1..${NUM_PUBLIC_SIGNALS}] concatenated (${NUM_PUBLIC_SIGNALS} x 64 bytes) for ec_multi_scalar_mul
    return Bytes.from_hex("${icRest}")
`;
writeFileSync(resolve(root, "contracts/verifier_key.py"), out);
console.log("wrote contracts/verifier_key.py");
